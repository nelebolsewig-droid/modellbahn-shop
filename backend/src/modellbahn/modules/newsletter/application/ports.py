"""What the newsletter's use cases need from the outside: repositories, the shop's
models, the readers' purchases and accounts, and their unit of work."""

from collections.abc import Callable, Collection, Sequence
from datetime import datetime
from types import TracebackType
from typing import Protocol, Self
from uuid import UUID

from modellbahn.modules.catalog.contracts.showcase import ShowcaseProduct
from modellbahn.modules.identity.contracts.accounts import AccountSummary
from modellbahn.modules.media.contracts.images import ImageView
from modellbahn.modules.newsletter.domain.model import Delivery, Issue, Subscription
from modellbahn.modules.sales.contracts.purchases import Purchase
from modellbahn.platform.events import DomainEvent


class SubscriptionRepository(Protocol):
    async def get(self, subscription_id: UUID) -> Subscription | None: ...
    async def by_account(
        self, account_id: UUID, *, for_update: bool = False
    ) -> Subscription | None: ...
    async def by_confirm_token(self, token_hash: str) -> Subscription | None: ...
    async def by_unsubscribe_token(self, token: str) -> Subscription | None: ...
    async def unsent(self, issue_id: UUID, limit: int) -> Sequence[Subscription]:
        """Confirmed subscriptions that have not had issue ``issue_id`` yet."""
        ...

    async def counts(self) -> dict[str, int]: ...
    def add(self, subscription: Subscription) -> None: ...
    async def delete(self, subscription: Subscription) -> None: ...
    async def delete_pending_before(self, moment: datetime) -> int: ...
    def record(self, delivery: Delivery) -> None: ...


class IssueRepository(Protocol):
    async def get(self, issue_id: UUID) -> Issue | None: ...
    async def latest(self) -> Issue | None: ...
    async def recent(self, limit: int) -> Sequence[tuple[Issue, int]]:
        """The latest issues with how many mails each went out as, the latest first."""
        ...

    def add(self, issue: Issue) -> None: ...


class Shop(Protocol):
    """The other modules, read inside the same transaction."""

    async def showcase(self) -> list[ShowcaseProduct]: ...
    async def purchases(self, account_id: UUID) -> frozenset[Purchase]: ...
    async def account(self, account_id: UUID) -> AccountSummary | None: ...
    async def images(self, asset_ids: Collection[UUID]) -> dict[UUID, ImageView]: ...


class NewsletterUnitOfWork(Protocol):
    """One transaction over the newsletter's repositories (see ``platform.uow``)."""

    @property
    def subscriptions(self) -> SubscriptionRepository: ...

    @property
    def issues(self) -> IssueRepository: ...

    @property
    def shop(self) -> Shop: ...

    async def __aenter__(self) -> Self: ...

    async def __aexit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        traceback: TracebackType | None,
    ) -> None: ...

    def publish(self, *events: DomainEvent) -> None: ...

    async def commit(self) -> None: ...


type UnitOfWorkFactory = Callable[[], NewsletterUnitOfWork]
