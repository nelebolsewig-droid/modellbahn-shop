"""Alembic environment: runs the hand-written migrations over asyncpg.

The database URL comes from ``MB_DATABASE_URL`` (via the application settings) unless
a caller such as the test suite passes one in ``config.attributes["database_url"]``.
There is no ``target_metadata``: migrations are never autogenerated.
"""

import asyncio
from logging.config import fileConfig

from alembic import context
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import create_async_engine
from sqlalchemy.pool import NullPool

from modellbahn.platform.config import Settings

config = context.config

if config.config_file_name is not None and config.attributes.get("configure_logging", True):
    fileConfig(config.config_file_name, disable_existing_loggers=False)


def _database_url() -> str:
    url = config.attributes.get("database_url")
    return url if isinstance(url, str) else Settings().database_url


def _run_migrations(connection: Connection) -> None:
    # One transaction per migration: PostgreSQL DDL is transactional, so a failing
    # migration leaves nothing half-applied.
    context.configure(connection=connection, transaction_per_migration=True)
    with context.begin_transaction():
        context.run_migrations()


async def _run_online() -> None:
    engine = create_async_engine(_database_url(), poolclass=NullPool)
    try:
        async with engine.connect() as connection:
            await connection.run_sync(_run_migrations)
    finally:
        await engine.dispose()


def _run_offline() -> None:
    context.configure(url=_database_url(), literal_binds=True)
    with context.begin_transaction():
        context.run_migrations()


if context.is_offline_mode():
    _run_offline()
else:
    asyncio.run(_run_online())
